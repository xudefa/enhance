package generator

import (
	"fmt"
	"strings"
	"text/template"
)

// StaticProxyTemplate 静态代理模板（零反射）
//
// 生成的代理代码直接内联通知链，完全消除运行时反射调用。
const StaticProxyTemplate = `// Code generated by enhance aop gen. DO NOT EDIT.
// source: {{.SourceFile}}

package {{.Package}}

import (
	{{- range .Imports}}
	"{{.}}"
	{{- end}}
)

// {{.ProxyName}} is the AOP proxy for {{.TargetName}}.
type {{.ProxyName}} struct {
	target *{{.TargetName}}
	{{- range .AdviceFields}}
	{{.Name}} {{.Type}}
	{{- end}}
}

// New{{.ProxyName}} creates a new proxy instance.
func New{{.ProxyName}}(target *{{.TargetName}} {{- range .AdviceFields}}, {{.Name}} {{.Type}}{{- end}}) *{{.ProxyName}} {
	return &{{.ProxyName}}{
		target: target,
		{{- range .AdviceFields}}
		{{.Name}}: {{.Name}},
		{{- end}}
	}
}

{{- range .Methods}}
{{- $method := .}}
func (p *{{$.ProxyName}}) {{.Name}}({{.ParamsStr}}) {{.ResultsStr}} {
{{- if .HasAspects}}
	// AOP advice chain for {{.Name}}
{{- if .BeforeAdvices}}
	// Before 通知
{{- range .BeforeAdvices}}
	p.{{.AdviceField}}[0](p.target{{if $method.HasParams}}, {{$method.ArgsList}}{{end}})
{{- end}}
{{- end}}
{{- if .HasReturnValue}}
	{{- if .AfterReturningAdvices}}
	result := p.target.{{.Name}}({{.ArgsList}})
	// AfterReturning advices
{{- range .AfterReturningAdvices}}
	p.{{.AdviceField}}[0](result)
{{- end}}
	return result
	{{- else}}
	return p.target.{{.Name}}({{.ArgsList}})
	{{- end}}
{{- else}}
	p.target.{{.Name}}({{.ArgsList}})
{{- if .AfterAdvices}}
	// After 通知
{{- range .AfterAdvices}}
	p.{{.AdviceField}}[0]()
{{- end}}
{{- end}}
	return
{{- end}}
{{- else}}
	{{- if .HasReturnValue}}
	return p.target.{{.Name}}({{.ArgsList}})
	{{- else}}
	p.target.{{.Name}}({{.ArgsList}})
	return
	{{- end}}
{{- end}}
}
{{- end}}
`

