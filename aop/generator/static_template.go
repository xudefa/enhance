// StaticProxyTemplateData 静态代理模板数据
type StaticProxyTemplateData struct {
	Package      string
	ProxyName    string
	TargetName   string
	SourceFile   string
	Imports      []string
	Methods      []StaticMethodInfo
	AdviceFields []AdviceField
}

// InterfaceProxyTemplateData 接口代理模板数据
type InterfaceProxyTemplateData struct {
	Package       string
	ProxyName     string
	InterfaceName string
	SourceFile    string
	Imports       []string
	Methods       []StaticMethodInfo
	AdviceFields  []AdviceField
}

// StaticMethodInfo 静态代理方法信息
type StaticMethodInfo struct {
	Name                  string
	Params                []ParamInfo
	Results               []string
	ParamsStr             string
	ResultsStr            string
	ArgsList              string
	HasParams             bool
	HasReturnValue        bool
	HasAspects            bool
	BeforeAdvices         []AdviceRef
	AfterAdvices          []AdviceRef
	AfterReturningAdvices []AdviceRef
	AroundAdvice          *AdviceRef
}

// AdviceField 通知字段
type AdviceField struct {
	Name string
	Type string
}

// AdviceRef 通知引用
type AdviceRef struct {
	AdviceField string
}
